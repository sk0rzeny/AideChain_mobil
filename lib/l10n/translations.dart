const String _kLocaleKey = 'app_locale';
final localeNotifier = ValueNotifier<Locale>(const Locale('fr'));

Future<void> loadSavedLocale() async {
  final prefs = await SharedPreferences.getInstance();
  final code = prefs.getString(_kLocaleKey) ?? 'fr';
  localeNotifier.value = Locale(code);
}

Future<void> setLocale(String code) async {
  final prefs = await SharedPreferences.getInstance();
  await prefs.setString(_kLocaleKey, code);
  localeNotifier.value = Locale(code);
}

String tr(String key) {
  final code = localeNotifier.value.languageCode;
  return _strings[code]?[key] ?? _strings['fr']?[key] ?? key;
}

